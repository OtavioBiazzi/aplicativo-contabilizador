import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import path from 'node:path';
import { PdvStore } from '../dist-electron/electron/pdvStore.js';
import { DEFAULT_TABLE_PREFERENCES, isOwnCloseNotice, shouldRemind, validTableExceptions, tableIsExcluded } from '../dist-electron/src/shared/closeReminders.js';
const directory=await mkdtemp(path.resolve('outputs/reminder-transfer-'));
const store=new PdvStore(directory); await store.initialize();
const notice={id:'closed-1',tableNumber:40,createdAt:new Date(2026,10,1,12).toISOString()};
assert.equal(shouldRemind(DEFAULT_TABLE_PREFERENCES,notice),false);
assert.equal(shouldRemind({...DEFAULT_TABLE_PREFERENCES,reminders:'weekdays'},notice),true);
assert.equal(shouldRemind({...DEFAULT_TABLE_PREFERENCES,reminders:'weekdays',weekdays:[2]},notice),false);
assert.equal(shouldRemind({...DEFAULT_TABLE_PREFERENCES,reminders:'always',excludedTables:'40'},notice),false);
assert.equal(DEFAULT_TABLE_PREFERENCES.reminderSource,'mine');assert.equal(DEFAULT_TABLE_PREFERENCES.syncAcknowledge,true);assert.equal(DEFAULT_TABLE_PREFERENCES.visibleLimit,4);
assert.ok(isOwnCloseNotice({...notice,originKind:'server'},'ipc'),'Server close is own on the server');
assert.ok(!isOwnCloseNotice({...notice,originKind:'client'},'ipc'),'Client close relayed to the server is not own');
assert.ok(isOwnCloseNotice(notice,'ipc'),'Legacy notices without origin stay local');
assert.ok(!isOwnCloseNotice({...notice,originKind:'server'},'network'),'Broadcasts are never own on a client');
assert.ok(isOwnCloseNotice({...notice,originKind:'client'},'self'),'Client own dispatch is own');
for(const expression of ['47','47+','001, 004, 021','10-15, 47+',''])assert.ok(validTableExceptions(expression));
for(const expression of ['xx','0','50-10','-2','47++'])assert.ok(!validTableExceptions(expression));
assert.ok(tableIsExcluded(900,'47+')); assert.ok(!tableIsExcluded(46,'47+')); assert.ok(tableIsExcluded(4,'004'));
const row=(quantity,total,measureLabel)=>({id:crypto.randomUUID(),productId:'qa',productName:'Ajuste QA',categoryName:'QA',quantity,unitPrice:10,discount:0,total,measureLabel});
const table=async n=>(await store.getSnapshot()).tables.find(t=>t.number===n);
const source=row(3,17.03);await store.openTable(1,1);await store.saveTableItems(1,[source],[],[]);
await store.transferTableItems(1,2,[{itemId:source.id,quantity:1}], 'transfer-custom');
assert.equal((await table(1)).total+(await table(2)).total,17.03,'Preserve adjusted total down to cents');
assert.equal((await table(2)).total,5.68);
const remaining=(await table(1)).items[0];await store.transferTableItems(1,3,[{itemId:remaining.id,quantity:remaining.quantity}], 'transfer-rest');
assert.equal((await table(3)).total,11.35,'Full transfer must preserve remainder, not catalog price');
await assert.rejects(store.saveTableItems(1,[remaining],[],[remaining.id]),/transferido|removido/);
const weighed=row(2.43,24.3,'2430 g');await store.openTable(4,1);await store.saveTableItems(4,[weighed],[],[]);
await store.transferTableItems(4,5,[{itemId:weighed.id,quantity:1}], 'transfer-weight');
assert.equal((await table(5)).items[0].measureLabel,'1000 g');assert.equal((await table(4)).items[0].measureLabel,'1430 g');
assert.equal((await table(4)).total+(await table(5)).total,24.3);
await store.closeTable(3,[{id:crypto.randomUUID(),method:'Pix',amount:11.35}],0,'QA','close-adjusted');
assert.equal((await table(3)).status,'Livre');
assert.equal((await store.closeTable(3,[{id:crypto.randomUUID(),method:'Pix',amount:11.35}],0,'QA','close-adjusted')).total,11.35);
await store.saveSettings({hideTableQuickValue:true});
const reloaded=new PdvStore(directory);await reloaded.initialize();
assert.equal(reloaded.getSettings().hideTableQuickValue,true,'Server rule for the + button must persist');
assert.equal(store.getSettings().allowOfflineTables===undefined||typeof store.getSettings().allowOfflineTables==='boolean',true);
console.log('PASS local reminder defaults/schedules/exceptions; transfer adjusted totals/weight/cents/stale save; durable idempotent close');
