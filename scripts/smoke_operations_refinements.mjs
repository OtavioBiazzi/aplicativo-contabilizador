import assert from "node:assert/strict";
import {mkdtemp,rm,readdir,readFile} from "node:fs/promises";
import JSZip from "jszip";
import path from "node:path";
import {tmpdir} from "node:os";
import {PdvStore} from "../dist-electron/electron/pdvStore.js";
import {historyPaymentAmount} from "../dist-electron/src/shared/paymentScope.js";
import {pdvSaleToLedgerEntry} from "../dist-electron/src/shared/pdvLedger.js";
import {createReportRecords,filterReportRecords,buildReportDataset} from "../dist-electron/src/shared/reporting.js";
import {PdvExporter} from "../dist-electron/electron/pdvExporter.js";
const dir=await mkdtemp(path.join(tmpdir(),"caixa-operations-"));
try {
  const old=new PdvStore(dir);await old.initialize();
  const legacy=await old.saveCustomer({name:"Cadastro antigo",active:true});
  const db=old.db;
  db.run("DROP INDEX idx_supplier_customer; ALTER TABLE suppliers DROP COLUMN customer_id; ALTER TABLE customers DROP COLUMN role; PRAGMA user_version=5");
  await old.persist();
  const store=new PdvStore(dir);await store.initialize();
  assert.equal(store.getCustomers().find(c=>c.id===legacy.id).role,"customer");
  assert((await readdir(path.join(dir,"pdv-backups"))).some(name=>name.includes("antes-migracao-v6")));
  const supplier=await store.saveCustomer({name:"Fornecedor vinculado",role:"supplier",active:true});
  assert.equal(store.getSuppliers().find(s=>s.customerId===supplier.id).name,supplier.name);
  const payable=await store.savePayable({supplier:supplier.name,amount:120,description:"Despesa"});
  const at="2026-10-20T13:12:00.000Z";
  const paid=await store.payPayable(payable.id,{id:crypto.randomUUID(),createdAt:at,method:"Pix",amount:40},"QA");
  assert.equal(paid.payments[0].createdAt,at);
  await assert.rejects(()=>store.payPayable(payable.id,{createdAt:"2026-02-30T10:00",method:"Pix",amount:1}),/data/i);
  await store.saveCustomer({...supplier,role:"both",name:"Fornecedor atualizado"});
  assert.equal(store.getSuppliers().filter(s=>s.customerId===supplier.id).length,1);
  assert.equal(store.getPayables().find(p=>p.id===payable.id).supplier,"Fornecedor vinculado");
  await store.saveCustomer({...supplier,role:"customer"});
  assert.equal(store.getSuppliers().some(s=>s.customerId===supplier.id),false);
  const customer=await store.saveCustomer({name:"Cliente e fornecedor",role:"both",active:true});
  const account=await store.saveReceivable({customerId:customer.id,description:"Conta",amount:60});
  assert.equal((await store.receiveReceivable(account.id,{createdAt:at,method:"Pix",amount:15})).payments[0].createdAt,at);
  for(const kind of ["payable","receivable"]) {
    const accounts=[];
    for(const amount of [20,30])accounts.push(kind==="payable"?await store.savePayable({supplier:"Grupo QA",amount}):await store.saveReceivable({customerId:customer.id,description:"Grupo QA",amount}));
    const payment={createdAt:at,method:"Pix",amount:38};
    const operation=crypto.randomUUID();
    const send=()=>kind==="payable"?store.paySupplierPayables("Grupo QA",payment,"QA",operation,accounts.map(a=>a.id)):store.receiveCustomerReceivables(customer.id,payment,"QA",operation,accounts.map(a=>a.id));
    const result=await send();
    assert.equal(result.reduce((sum,a)=>sum+a.balance,0),12);
    assert(result.every(a=>a.payments.every(p=>p.createdAt===at)));
    assert.equal((await send()).reduce((sum,a)=>sum+a.payments.length,0),2);
  }
  const category=await store.saveCategory({name:"QA",active:true,favorite:false,sortOrder:0});
  const product=await store.saveProduct({name:"Café QA",categoryId:category.id,price:30,active:true,showOnPdv:true,unit:"UNID",unitMode:"unidade"});
  const other=await store.saveProduct({name:"Outro QA",categoryId:category.id,price:5,active:true,showOnPdv:true,unit:"UNID",unitMode:"unidade"});
  const item=(p,quantity)=>({id:crypto.randomUUID(),productId:p.id,productName:p.name,categoryName:"QA",quantity,unitPrice:p.price,total:p.price*quantity,discount:0});
  await store.openTable(1,1);
  await store.saveTableItems(1,[item(product,2)],[],[]);
  const sale=await store.closeTable(1,[{id:crypto.randomUUID(),method:"Credito",amount:30,description:"Credito"},{id:crypto.randomUUID(),method:"Debito",amount:30}]);
  const ledger=pdvSaleToLedgerEntry(sale);
  assert.equal(historyPaymentAmount(ledger,"Credito"),30);
  assert.equal(historyPaymentAmount(ledger,"Debito"),30);
  assert.equal(historyPaymentAmount(ledger,"Pix"),0);
  assert.equal(historyPaymentAmount(ledger,"Todos"),60);
  const dataset=buildReportDataset(filterReportRecords(createReportRecords([ledger],[sale]),{payment:"Credito"}));
  assert.equal(dataset.records[0].total,30);
  assert.equal(dataset.records[0].payments.length,1);
  assert.equal(dataset.products.reduce((sum,p)=>sum+p.revenue,0),30);
  const exported=await new PdvExporter(path.join(dir,"reports")).exportSales([sale],{payment:"Credito"});
  assert.equal(exported.ok,true);
  const zip=await JSZip.loadAsync(await readFile(exported.filePath));
  const xml=await zip.file("xl/worksheets/sheet1.xml").async("string");
  const totalRow=xml.match(/<row\b[^>]*>[\s\S]*?<\/row>/g).find(row=>row.includes("Total vendido"));
  assert.match(totalRow,/<v>30<\/v>/,"Filtered Excel must not count the debit portion");
  await store.openTable(16,2);await store.saveTableItems(16,[item(other,1)],[],[]);
  const live=await store.getTable(16);
  await store.updateSale(sale.id,{tableNumber:"016"});
  let updated=store.getSaleById(sale.id);
  assert.equal(updated.tableNumber,16);
  assert.match(updated.description,/Mesa 16/);
  assert.equal(updated.tableSessionId,sale.tableSessionId);
  assert.deepEqual(await store.getTable(16),live);
  await store.updateSale(sale.id,{description:"Credito"});
  updated=await store.updateSalePayments(sale.id,sale.payments.map((p,i)=>i===0?{...p,method:"Pix"}:p));
  assert.equal(updated.description,"Pix");
  assert.equal(updated.payments[0].description,"Pix");
  assert.equal(updated.total,60);
  await store.saveSettings({frequentCategoryEnabled:true});
  let snap=await store.getSnapshot();assert.equal(snap.frequentProductIds[0],product.id);
  const second=await store.saveSale({type:"Venda direta",items:[item(other,3)],discount:0,payments:[{id:crypto.randomUUID(),method:"Pix",amount:15}]});
  assert.equal((await store.getSnapshot()).frequentProductIds[0],other.id);
  await store.cancelSale(second.id);
  assert.equal((await store.getSnapshot()).frequentProductIds[0],product.id);
  await store.updateProducts([product.id],{showOnPdv:false});
  assert.equal((await store.getSnapshot()).frequentProductIds.includes(product.id),false);
  const restarted=new PdvStore(dir);await restarted.initialize();
  assert.equal((await restarted.getSnapshot()).settings.frequentCategoryEnabled,true);
  assert.equal(restarted.getCustomers().find(c=>c.id===customer.id).role,"both");
  console.log("PASS v5->v6 backup, contact roles, dated/grouped settlements and replay, exact payment filters/reports, historical table edit, generated descriptions and frequent ranking/cache");
} finally {await rm(dir,{recursive:true,force:true});}
