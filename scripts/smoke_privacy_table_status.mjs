import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { PdvStore } from "../dist-electron/electron/pdvStore.js";
import { privacyProfiles, applyPrivacyProfile, togglePrivacy, historyValuesHidden, sharedPrivacyDefinitions, mergeRemotePrivacy } from "../dist-electron/src/shared/privacy.js";
const initial = { hideHeaderTotal: false, hideReportTotals: false };
const profiles = privacyProfiles(initial);
const custom = { id: "custom", name: "Balcão pesquisável", hideHeaderTotal: true, hideReportTotals: false, historyValues: "search" };
let privacy = { ...initial, profiles: [...profiles, custom], enabledProfileId: "custom", disabledProfileId: "normal" };
privacy = togglePrivacy(privacy);
assert.equal(privacy.activeProfileId, "custom");
assert.equal(privacy.hideHeaderTotal, true);
assert.equal(privacy.hideReportTotals, false);
assert.equal(historyValuesHidden(privacy, false), true);
assert.equal(historyValuesHidden(privacy, true), false);
privacy = togglePrivacy(privacy);
assert.equal(privacy.activeProfileId, "normal");
assert.equal(historyValuesHidden(privacy, false), false);
assert.equal(historyValuesHidden(applyPrivacyProfile(privacy, "private"), true), true);
assert.equal(historyValuesHidden({ hideHeaderTotal: true, hideReportTotals: false }, false), true, "Legacy privacy is retained");
const shared = sharedPrivacyDefinitions({ ...privacy, enabled: true });
assert.equal("enabled" in shared, false);
const localEnabled = mergeRemotePrivacy({ ...privacy, enabled: true }, shared);
const localDisabled = mergeRemotePrivacy({ ...privacy, enabled: false, activeProfileId: "normal" }, shared);
assert.equal(localEnabled.enabled, true);
assert.equal(localDisabled.enabled, false);
assert.deepEqual(localEnabled.profiles, localDisabled.profiles);
assert.equal(shared.enabledProfileId, "custom");
const directory = await mkdtemp(path.join(tmpdir(), "caixa-status-"));
try {
  const store = new PdvStore(directory); await store.initialize();
  await store.setTableStatus(1, "Fechamento");
  let table = (await store.getSnapshot()).tables.find(t => t.number === 1);
  assert.equal(table.status, "Fechamento", "Explicit empty-table closing must not become Livre");
  assert.equal(table.people, 0);
  await store.setTableStatus(1, "Livre");
  assert.equal((await store.getSnapshot()).tables.find(t => t.number === 1).status, "Livre");
  await store.openTable(2, 2);
  const item = { id: "qa-item", productId: "qa-product", productName: "Café", categoryName: "Café", quantity: 1, unitPrice: 10, total: 10, discount: 0, subtableName: "Ana" };
  await store.saveTableItems(2, [item], ["Ana"], []);
  await store.setTableStatus(2, "Fechamento");
  assert.equal((await store.getSnapshot()).tables.find(t => t.number === 2).status, "Fechamento");
  await store.saveTableItems(2, [{ ...item, quantity: 2, total: 20 }], ["Ana"], [item.id]);
  assert.equal((await store.getSnapshot()).tables.find(t => t.number === 2).status, "Fechamento", "Saving items preserves closing");
  const reopened = new PdvStore(directory); await reopened.initialize();
  assert.equal((await reopened.getSnapshot()).tables.find(t => t.number === 2).status, "Fechamento", "Closing survives restart");
  console.log("smoke_privacy_table_status: ok");
} finally { await rm(directory, { recursive: true, force: true }); }
