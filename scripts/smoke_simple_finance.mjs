import assert from 'node:assert/strict';
import { mkdtemp, readdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { PdvStore } from '../dist-electron/electron/pdvStore.js';

const dir = await mkdtemp(path.join(os.tmpdir(), 'caixa-simple-finance-'));
let store = new PdvStore(dir); await store.initialize();
const dueDate = '2026-12-01';
const first = await store.savePayable({ description:'Compra antiga', supplier:'Fornecedor Antigo', amount:50, dueDate, category:'Bebidas', costCenter:'Loja', paymentAccount:'Dado anterior preservado', tags:['antiga'], preferredPaymentMethod:'Credito' });
assert.equal(first.preferredPaymentMethod,'Credito');
await store.payPayable(first.id,{id:crypto.randomUUID(),payableId:first.id,createdAt:new Date().toISOString(),method:'Pix',amount:10},'Cliente','simple-first');
const db = store.requireDb();
db.run('DROP TABLE suppliers');
db.run("DELETE FROM pdv_settings WHERE key = 'supplier_registry_initialized'");
db.run('ALTER TABLE payables DROP COLUMN preferred_payment_method');
db.run('PRAGMA user_version = 3');
await store.persist();

store = new PdvStore(dir); await store.initialize();
let account = store.getPayables().find(item=>item.id===first.id);
assert.equal(account.preferredPaymentMethod,'');
assert.equal(account.balance,40);
assert.equal(account.payments.length,1);
assert.equal(account.paymentAccount,'Dado anterior preservado');
assert((await readdir(path.join(dir,'pdv-backups'))).some(name=>name.includes('antes-migracao-v5')));
const migrated = store.getSuppliers().find(item=>item.name==='Fornecedor Antigo');
assert(migrated);
await store.deleteSupplier(migrated.id);
store = new PdvStore(dir); await store.initialize();
assert.equal(store.getSuppliers().length,0,'A exclusão do fornecedor não pode ser desfeita pela migração ao reiniciar.');
account = await store.savePayable({...account,preferredPaymentMethod:'Debito'});
assert.equal(store.getSuppliers().length,0,'Editar a conta antiga não recria o cadastro removido.');
assert.equal(account.preferredPaymentMethod,'Debito');
assert.equal(account.supplier,'Fornecedor Antigo');
assert.equal(account.payments.length,1);
assert.equal(account.category,'Bebidas');
assert.equal(account.paymentAccount,'Dado anterior preservado');
const supplier = await store.saveSupplier({id:crypto.randomUUID(),name:'  Distribuidora Nova  '});
const duplicate = await store.saveSupplier({id:crypto.randomUUID(),name:'distribuidora nova'});
assert.equal(supplier.id,duplicate.id);
const next = await store.savePayable({description:'Compra nova',supplier:supplier.name,amount:25,dueDate});
assert.equal(next.preferredPaymentMethod,'');
await store.deleteSupplier(supplier.id);
assert(store.getPayables().some(item=>item.id===next.id && item.supplier===supplier.name));
await assert.rejects(store.savePayable({...next,preferredPaymentMethod:'Invalida'}),/Forma de pagamento/);
store = new PdvStore(dir); await store.initialize();
assert.equal(store.getPayables().find(item=>item.id===first.id).preferredPaymentMethod,'Debito');
assert.equal(store.getSuppliers().length,0);
console.log('Simple finance smoke passed: v3 migration, backup, defaults, metadata/payments, supplier uniqueness, deletion and restart.');
