import assert from 'node:assert/strict';
import { mkdtemp, readdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { PdvStore } from '../dist-electron/electron/pdvStore.js';
import { payableLabel } from '../dist-electron/src/shared/financialLabels.js';

const dir=await mkdtemp(path.join(os.tmpdir(),'caixa-optional-payable-'));
let store=new PdvStore(dir);await store.initialize();
const original=await store.savePayable({description:'Conta antiga',supplier:'Fornecedor',category:'Bebidas',costCenter:'Loja',amount:100,dueDate:'2026-12-01',preferredPaymentMethod:'Credito'});
await store.payPayable(original.id,{id:crypto.randomUUID(),payableId:original.id,createdAt:new Date().toISOString(),method:'Pix',amount:25},'Servidor','optional-partial');
const db=store.requireDb();
db.run('DROP TABLE financial_lookups');
db.run("DELETE FROM pdv_settings WHERE key='financial_lookups_initialized'");
db.run('PRAGMA user_version=4');await store.persist();
store=new PdvStore(dir);await store.initialize();
assert((await readdir(path.join(dir,'pdv-backups'))).some(name=>name.includes('antes-migracao-v5')));
assert(store.getFinancialLookups().some(x=>x.kind==='category' && x.name==='Bebidas'));
assert(store.getFinancialLookups().some(x=>x.kind==='costCenter' && x.name==='Loja'));
let old=store.getPayables().find(x=>x.id===original.id);
assert.equal(old.balance,75);assert.equal(old.preferredPaymentMethod,'Credito');
old=await store.savePayable({...old,description:'',dueDate:'',preferredPaymentMethod:''});
assert.equal(old.balance,75);assert.equal(old.preferredPaymentMethod,'');assert.equal(old.status,'Parcialmente paga');
assert.equal(payableLabel(old),'Fornecedor');
const minimal=await store.savePayable({amount:20});
assert.equal(minimal.preferredPaymentMethod,'');assert.equal(minimal.status,'Em aberto');assert.equal(minimal.balance,20);
assert.equal(payableLabel(minimal),'Conta a pagar');
assert.equal(payableLabel({...minimal,documentNumber:'NF-10'}),'Documento NF-10');
await assert.rejects(store.savePayable({description:'',amount:0,dueDate:''}),/valor maior/);
await assert.rejects(store.savePayable({description:'',amount:10,dueDate:'invalida'}),/vencimento/);
const category=store.getFinancialLookups().find(x=>x.kind==='category');
await store.deleteFinancialLookup(category.id);
old=await store.savePayable({...old,note:'Edição preserva classificação antiga'});
store=new PdvStore(dir);await store.initialize();
assert(!store.getFinancialLookups().some(x=>x.id===category.id),'A classificação excluída não deve reaparecer ao editar ou reiniciar.');
assert.equal(store.getPayables().find(x=>x.id===old.id).category,'Bebidas');
const created=await store.saveFinancialLookup({id:crypto.randomUUID(),kind:'category',name:'Aluguel'});
assert.equal((await store.saveFinancialLookup({id:crypto.randomUUID(),kind:'category',name:' aluguel '})).id,created.id);
const center=await store.saveFinancialLookup({id:crypto.randomUUID(),kind:'costCenter',name:'Aluguel'});
assert.notEqual(center.id,created.id);
await assert.rejects(store.saveFinancialLookup({kind:'invalido',name:'Teste'}),/Tipo de cadastro/);
const withoutDue=await store.savePayable({description:'',supplier:'Grupo',amount:10,dueDate:'',issueDate:'2020-01-01'});
const withDue=await store.savePayable({description:'',supplier:'Grupo',amount:30,dueDate:'2030-01-01'});
const result=await store.paySupplierPayables('Grupo',{id:crypto.randomUUID(),payableId:'',createdAt:new Date().toISOString(),method:'Pix',amount:15},'Servidor','optional-group');
assert.equal(result.find(x=>x.id===withoutDue.id).balance,0);assert.equal(result.find(x=>x.id===withDue.id).balance,25);
console.log('Optional payable smoke passed: v4 migration, empty fields/default, partial balance, labels, classification registries, permissions-independent validation and undated allocation.');
